import assert from 'node:assert/strict'
import {mkdir,readFile} from 'node:fs/promises'
import {chromium} from 'playwright'
import {guideFilename,guideIds} from '../src/guides.mjs'
import {createHash,randomBytes} from 'node:crypto'
import {DatabaseSync} from 'node:sqlite'

const base = process.env.NC_URL || 'http://127.0.0.1:5173'
const browser = await chromium.launch({channel:process.env.NC_BROWSER || 'chrome'})
const directory = '.local/verification'
await mkdir(directory+'/guides',{recursive:true})
const db = new DatabaseSync('.local/northeast.sqlite')
const legacyCode = randomBytes(24).toString('base64url')
const legacyDigest = createHash('sha256').update(legacyCode).digest('hex')
const legacyAddress = 'Legacy practice river embankment'
db.prepare("insert into records(bucket,code,payload) values ('requests',?,?)").run(legacyDigest,JSON.stringify({
  state:'Assam',district:'Dhemaji',landmark:legacyAddress,type:'Evacuation',people:1,callback:'0000000001',
  status:'Acknowledged',public_update:'Legacy public note.',private_notes:'Legacy private note.',demo:true,
  updated_at:'2026-11-20T04:00:00.000Z'
}))
try {
  const resident = await browser.newContext({viewport:{width:390,height:844},acceptDownloads:true,geolocation:{latitude:27.48316,longitude:94.55737},permissions:['geolocation','clipboard-read','clipboard-write']})
  const admin = await browser.newContext()
  const user = await resident.newPage()
  const staff = await admin.newPage()
  user.setDefaultTimeout(10000)
  staff.setDefaultTimeout(10000)
  const database = await resident.request.get(base+'/.local/northeast.sqlite')
  assert.ok([403,404].includes(database.status()))
  const timestamp = Date.now()
  const locality = 'Verification locality '+timestamp
  const landmark = 'Verification community hall'
  const title = 'Verification alert '+timestamp
  const update = 'Practice coordinator acknowledged the request.'
  const errors = []
  for (const page of [user,staff]) page.on('pageerror',error=>errors.push(error.message))
  for (const table of ['requests','alerts','resources']) {
    assert.equal((await resident.request.get(base+'/api/admin/'+table)).status(),401)
    assert.equal((await resident.request.post(base+'/api/admin/'+table,{data:{}})).status(),401)
  }
  await user.goto(base)
  await user.getByRole('heading',{name:'Latest local alerts'}).waitFor()
  assert.equal(await user.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true)
  await user.screenshot({path:directory+'/phone-home.png',fullPage:true})
  await user.getByRole('link',{name:'Track My Report',exact:true}).waitFor()
  await user.getByLabel('District',{exact:true}).selectOption('Dhemaji')
  await user.getByRole('link',{name:/^Request Help/}).click()
  assert.equal(await user.getByLabel('State',{exact:true}).inputValue(),'Assam')
  assert.equal(await user.getByLabel('District',{exact:true}).inputValue(),'Dhemaji')
  await user.getByLabel('State',{exact:true}).selectOption('Meghalaya')
  await user.getByLabel('District',{exact:true}).fill('East Khasi Hills')
  await user.getByLabel('State',{exact:true}).selectOption('Assam')
  await user.getByLabel('District',{exact:true}).selectOption('Dhemaji')
  await user.getByLabel('Village, town, or locality').fill(locality)
  await user.getByText('More address details (optional)').click()
  for (const [label,value] of [
    ['Block or subdivision','Verification block'],['Ward or gram panchayat','Ward 2'],['Road or lane','Practice lane'],
    ['House or building number','B-10'],['Nearest landmark',landmark],['PIN code','787057']
  ]) await user.getByLabel(label,{exact:true}).fill(value)
  await user.getByRole('button',{name:'Use my location'}).click()
  await user.getByText(/Coordinates attached/).waitFor()
  assert.equal(await user.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true)
  await user.screenshot({path:directory+'/phone-request.png',fullPage:true})
  await user.getByLabel('Assistance type').selectOption('Evacuation')
  await user.getByLabel('People affected').fill('3')
  await user.getByLabel('Callback number').fill('0000000000')
  await user.getByRole('button',{name:'Submit help request'}).click()
  const code = await user.locator('output').textContent()
  assert.match(code,/^[\w-]{32}$/)
  await user.getByRole('button',{name:'Copy code'}).click()
  await user.getByText('Tracking code copied.').waitFor()
  assert.equal(await user.evaluate(()=>navigator.clipboard.readText()),code)
  await user.getByRole('link',{name:'Track this report',exact:true}).click()
  assert.equal(await user.getByLabel('Tracking code').inputValue(),code)
  assert.equal(user.url(),base+'/#track')
  await staff.goto(base+'/#admin')
  await staff.getByLabel('Email').fill(process.env.DEMO_ADMIN_EMAIL || 'admin@northeast.test')
  await staff.getByLabel('Password').fill(process.env.DEMO_ADMIN_PASSWORD || 'Northeast-Demo-2026!')
  await staff.getByRole('button',{name:'Sign in',exact:true}).click()
  await staff.getByLabel('District',{exact:true}).selectOption('Dhemaji')
  await staff.getByLabel('Assistance type').selectOption('Evacuation')
  const legacyCard = staff.locator('article').filter({hasText:legacyAddress})
  await legacyCard.getByText('Incident address:',{exact:true}).waitFor()
  await staff.getByLabel('Status',{exact:true}).selectOption('Submitted')
  const newCard = staff.locator('article').filter({hasText:locality})
  await newCard.getByText('B-10, Practice lane, '+landmark+', Ward 2, '+locality+', Verification block, Dhemaji, Assam, PIN 787057',{exact:false}).waitFor()
  await newCard.getByText('27.48316, 94.55737',{exact:false}).waitFor()
  await newCard.getByRole('button',{name:'Edit'}).click()
  const editor = staff.locator('.editor')
  await editor.getByLabel('Status',{exact:true}).selectOption('Acknowledged')
  await editor.getByLabel(/Public update/).fill(update)
  await editor.getByLabel(/Private notes/).fill('Private verification note.')
  await editor.getByRole('button',{name:'Save changes'}).click()
  await staff.getByText('Changes saved.').waitFor()
  const tracker = await browser.newContext({viewport:{width:390,height:844}})
  const tracking = await tracker.newPage()
  tracking.setDefaultTimeout(10000)
  tracking.on('pageerror',error=>errors.push(error.message))
  await tracking.goto(base)
  await tracking.getByRole('link',{name:'Track My Report',exact:true}).click()
  const codeInput = tracking.getByLabel('Tracking code')
  assert.equal(await codeInput.inputValue(),'')
  await codeInput.fill('invalid')
  await tracking.getByRole('button',{name:'Check status'}).click()
  await tracking.getByText(/No report was found/).waitFor()
  await codeInput.fill(code)
  await tracking.getByRole('button',{name:'Check status'}).click()
  await tracking.getByText(update,{exact:true}).waitFor()
  assert.equal(await tracking.locator('.tracking-result .badge.green').textContent(),'Acknowledged')
  const raw = await (await tracker.request.post(base+'/api/track',{data:{code}})).json()
  assert.deepEqual(Object.keys(raw).sort(),['demo','events','history_incomplete','legacy_note','status','submitted_at','updated_at'])
  assert.deepEqual(raw.events.map(event=>[event.kind,event.status,event.note]),[['status','Submitted',''],['status','Acknowledged',update]])
  assert.ok(raw.submitted_at && raw.updated_at)
  for (const event of raw.events) assert.deepEqual(Object.keys(event).sort(),['at','kind','note','status'])
  for (const value of [locality,landmark,'0000000000','Private verification note.','27.48316']) assert.ok(!JSON.stringify(raw).includes(value))
  await staff.getByLabel('Status',{exact:true}).selectOption('')
  await newCard.getByRole('button',{name:'Edit'}).click()
  await editor.getByLabel('Status',{exact:true}).selectOption('In Progress')
  await editor.getByLabel(/Public update/).fill('Practice crew assigned.')
  await editor.getByRole('button',{name:'Save changes'}).click()
  await staff.getByText('Changes saved.').waitFor()
  assert.equal(await tracking.locator('.tracking-result .badge.green').textContent(),'Acknowledged')
  await tracking.getByRole('button',{name:'Refresh status'}).click()
  await tracking.getByText('Practice crew assigned.',{exact:true}).waitFor()
  await tracking.getByText(update,{exact:true}).waitFor()
  assert.equal(await tracking.locator('.tracking-result .badge.green').textContent(),'In Progress')
  await tracking.screenshot({path:directory+'/phone-tracking.png',fullPage:true})
  await tracking.route('**/api/track',route=>route.abort())
  await tracking.getByRole('button',{name:'Refresh status'}).click()
  await tracking.getByText(/Status lookup failed/).waitFor()
  await tracking.unroute('**/api/track')
  await codeInput.fill(legacyCode)
  await tracking.getByRole('button',{name:'Check status'}).click()
  await tracking.getByText('Legacy public note.',{exact:true}).waitFor()
  await tracking.getByText('Submission time not recorded',{exact:true}).waitFor()
  await tracking.getByText('No timeline events recorded yet.',{exact:true}).waitFor()
  const old = await (await tracker.request.post(base+'/api/track',{data:{code:legacyCode}})).json()
  assert.ok(old.history_incomplete)
  assert.deepEqual(old.events,[])
  assert.equal(old.status,'Acknowledged')
  assert.ok(!JSON.stringify(old).includes(legacyAddress) && !JSON.stringify(old).includes('Legacy private note.'))
  await tracking.goto(base+'/#request')
  await tracking.getByRole('button',{name:'Use my location'}).click()
  await tracking.getByText(/Location could not be shared/).waitFor()
  assert.ok(await tracking.getByLabel('Village, town, or locality').isEnabled())
  console.log('Passed mobile structured reports, coordinate sharing and denial, copy and prefill, signed-out tracking, legacy reports, timeline, and privacy.')
  await staff.getByRole('button',{name:'Manage alerts'}).click()
  await staff.getByRole('button',{name:'Add alert'}).click()
  await editor.getByLabel('District').selectOption('Dhemaji')
  await editor.getByLabel('Alert title').fill(title)
  await editor.getByLabel('Affected area').fill('Practice riverbank')
  await editor.getByLabel('Instructions').fill('Practice only. Follow authority instructions.')
  await editor.getByLabel('Issuing source').fill('Demo district bulletin')
  await editor.getByRole('button',{name:'Save changes'}).click()
  await staff.getByText('Changes saved.').waitFor()
  assert.equal((await (await resident.request.get(base+'/api/alerts')).json()).some(row=>row.title===title),false)
  await staff.locator('article').filter({hasText:title}).getByRole('button',{name:'Edit'}).click()
  await editor.getByLabel('Publication').selectOption('Published')
  await editor.getByRole('button',{name:'Save changes'}).click()
  await staff.getByText('Changes saved.').waitFor()
  await user.goto(base+'/#alerts')
  await user.getByLabel('District').selectOption('Dhemaji')
  await user.getByRole('heading',{name:title}).waitFor()
  await user.getByLabel('District').selectOption('Cachar')
  await user.getByRole('heading',{name:title}).waitFor({state:'hidden'})
  await staff.locator('article').filter({hasText:title}).getByRole('button',{name:'Edit'}).click()
  await editor.getByLabel('Publication').selectOption('Expired')
  await editor.getByRole('button',{name:'Save changes'}).click()
  await staff.getByText('Changes saved.').waitFor()
  assert.equal((await (await resident.request.get(base+'/api/alerts')).json()).some(row=>row.title===title),false)

  await staff.getByRole('button',{name:'Manage resources'}).click()
  const resource = staff.locator('article').filter({hasText:'Dhemaji practice medical post'})
  const originalAvailability = await resource.locator('.badge').first().textContent()
  await resource.getByRole('button',{name:'Edit'}).click()
  await editor.getByLabel('Availability').selectOption('Closed')
  await editor.getByRole('button',{name:'Save changes'}).click()
  await staff.getByText('Changes saved.').waitFor()
  await user.goto(base+'/#resources')
  await user.getByLabel('District').selectOption('Dhemaji')
  await user.locator('article').filter({hasText:'Dhemaji practice medical post'}).getByText('Closed',{exact:true}).waitFor()
  await resource.getByRole('button',{name:'Edit'}).click()
  await editor.getByLabel('Availability').selectOption(originalAvailability)
  await editor.getByRole('button',{name:'Save changes'}).click()
  await staff.getByText('Changes saved.').waitFor()
  await staff.getByRole('button',{name:'Sign out'}).click()
  await staff.getByRole('heading',{name:'Administrator sign-in'}).waitFor()
  assert.equal((await admin.request.get(base+'/api/admin/requests')).status(),401)

  console.log('Passed request, tracking, alert, resource, and authorization flows.')
  for (const language of ['en','as','bn','hi']) {
    const downloads = await browser.newContext({acceptDownloads:true})
    const guidePage = await downloads.newPage()
    await guidePage.goto(base+'/#awareness')
    await guidePage.getByLabel('Guide language').selectOption(language)
    const links = guidePage.locator('.guide a[download]')
    assert.equal(await guidePage.locator('article[lang="'+language+'"]').count(),4)
    assert.equal(await links.count(),4)
    for (const [index,id] of guideIds.entries()) {
      const [file] = await Promise.all([guidePage.waitForEvent('download',{timeout:10000}),links.nth(index).click()])
      const filename = guideFilename(id,language)
      assert.equal(file.suggestedFilename(),filename)
      await file.saveAs(directory+'/guides/'+filename)
      const bytes = await readFile(await file.path())
      assert.equal(bytes.subarray(0,5).toString(),'%PDF-')
      assert.deepEqual(bytes,await readFile('public/guides/'+language+'/'+filename))
    }
    await downloads.close()
  }
  await user.goto(base+'/#awareness')
  await user.getByLabel('Guide language').selectOption('hi')
  await user.reload()
  assert.equal(await user.getByLabel('Guide language').inputValue(),'hi')
  assert.equal(await user.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true)
  await user.screenshot({path:directory+'/phone-awareness.png',fullPage:true})
  assert.deepEqual(errors,[])
  console.log('Passed: mobile layouts, submission, admin queue and update, tracking privacy, draft/publish/expire by district, resource updates, signed-out API denial, and all 16 PDF downloads.')
} finally {
  await browser.close()
  db.prepare('delete from records where code=?').run(legacyDigest)
  db.close()
}
